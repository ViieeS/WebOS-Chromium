#!/usr/bin/env python3
"""Writes tv-stubs.xml: the wayland protocol definitions of the TV's own client libraries for the interfaces the TV's LSM offers and LG's
open-source (OSE) protocol files do not define (wl_webos_xinput, wl_starfish_output/pointer, text_model_factory and the objects it creates, linux-dmabuf). The definitions
are read from the TV's files, not from upstream, so the request/event order and argument types match what the TV's clients send.

It must run with the TV's own python3 and libraries (32-bit ctypes layout), on a TV or in a container with a copy of
its root filesystem: python3 - < gen-tv-stubs.py > tv-stubs.xml
Interfaces defined by the OSE protocol files in /opt/twin/protocol (KEPT_XML) are skipped; core wayland objects are referenced only.
"""
import ctypes as C
import glob
import re
import sys

ROOTS = ["wl_webos_surface_group_compositor", "wl_webos_xinput", "wl_webos_xinput_extension", "wl_starfish_output", "wl_starfish_pointer",
         "text_model_factory", "zwp_linux_dmabuf_v1", "zwp_linux_buffer_params_v1"]
# the OSE XML files that are kept: their wire definitions match the TV's libraries (checked on a TV). webos-extension.xml and
# webos-surface-group.xml (LG's copies) differed from the TV's libraries, so their interfaces come from the TV's libraries here instead.
KEPT_XML = ("webos-shell.xml", "webos-input-manager.xml", "webos-foreign.xml")
LIBS = ["/usr/lib/libwayland-webos-client.so.1.0.0", "/usr/lib/libwayland-starfish-client.so.1.0.0",
        "/usr/lib/plugins/wayland-graphics-integration-server/liblinux-dmabuf-unstable-v1.so"]
def quoteattr(v):
    return '"%s"' % v.replace("&", "&amp;").replace("<", "&lt;").replace('"', "&quot;")


# core wayland objects (wayland.xml): the TV's libraries carry copies, the compositor gets them from libwayland-server
CORE = {"wl_surface", "wl_buffer", "wl_callback", "wl_region", "wl_output", "wl_seat", "wl_pointer", "wl_keyboard", "wl_touch"}

TYPE = {"i": "int", "u": "uint", "f": "fixed", "s": "string", "o": "object", "n": "new_id", "a": "array", "h": "fd"}


class Msg(C.Structure):
    _fields_ = [("name", C.c_char_p), ("signature", C.c_char_p), ("types", C.POINTER(C.c_void_p))]


class Iface(C.Structure):
    _fields_ = [("name", C.c_char_p), ("version", C.c_int), ("method_count", C.c_int), ("methods", C.POINTER(Msg)),
                ("event_count", C.c_int), ("events", C.POINTER(Msg))]


def existing_names():
    out = set()
    for f in [x for x in glob.glob("/opt/twin/protocol/*.xml") if x.rsplit("/", 1)[1] in KEPT_XML]:
        out |= set(re.findall(r'<interface name="([^"]+)"', open(f).read()))
    return out


def load(libs):
    found = {}
    handles = []
    for lib in libs:
        try:
            handles.append(C.CDLL(lib, mode=C.RTLD_GLOBAL))
        except OSError as e:
            sys.stderr.write("skip %s: %s\n" % (lib, e))
    def get(name):
        if name in found:
            return found[name]
        for h in handles:
            try:
                found[name] = Iface.in_dll(h, name + "_interface")
                return found[name]
            except ValueError:
                continue
        return None
    return get


def main():
    get = load(LIBS)
    skip = existing_names()
    todo, seen, out = list(ROOTS), set(), []
    while todo:
        name = todo.pop(0)
        if name in seen or name in skip:
            continue
        seen.add(name)
        i = get(name)
        if i is None:
            sys.stderr.write("not in the TV libraries: %s\n" % name)
            continue
        if name not in CORE:          # core objects come from libwayland itself: referenced, never redefined
            out.append(i)
        for count, msgs in ((i.method_count, i.methods), (i.event_count, i.events)):
            for k in range(count):
                m = msgs[k]
                sig = (m.signature or b"").decode().lstrip("0123456789")
                ti = 0
                for ch in sig:
                    if ch in "?0123456789":
                        continue
                    if ch in "on":
                        p = m.types[ti]
                        if p:
                            ref = Iface.from_address(p).name.decode()
                            if ref not in seen:
                                todo.append(ref)
                    ti += 1
    print('<?xml version="1.0" encoding="UTF-8"?>')
    print('<!-- generated by gen-tv-stubs.py from the TV libraries %s -->' % " ".join(l.rsplit("/", 1)[1] for l in LIBS))
    print('<protocol name="tv_stubs">')
    for i in out:
        print('  <interface name=%s version="%d">' % (quoteattr(i.name.decode()), i.version))
        for kind, n, msgs in (("request", i.method_count, i.methods), ("event", i.event_count, i.events)):
            for k in range(n):
                m = msgs[k]
                sig = (m.signature or b"").decode()
                since = re.match(r"\d*", sig).group(0)
                body = sig.lstrip("0123456789")
                args, ti, nullable = [], 0, False
                for ch in body:
                    if ch == "?":
                        nullable = True
                        continue
                    attrs = ' name="a%d" type="%s"' % (len(args), TYPE[ch])
                    if ch in "on":
                        p = m.types[ti]
                        if p:
                            attrs += " interface=%s" % quoteattr(Iface.from_address(p).name.decode())
                    if nullable:
                        attrs += ' allow-null="true"'
                    args.append("      <arg%s/>" % attrs)
                    nullable = False
                    ti += 1
                s_attr = ' since="%d"' % int(since) if since and int(since) > 1 else ""
                if kind == "request" and m.name.decode() == "destroy":
                    s_attr += ' type="destructor"'      # wayland-scanner requires it on the request that destroys the object
                if args:
                    print('    <%s name=%s%s>' % (kind, quoteattr(m.name.decode()), s_attr))
                    print("\n".join(args))
                    print("    </%s>" % kind)
                else:
                    print('    <%s name=%s%s/>' % (kind, quoteattr(m.name.decode()), s_attr))
        print("  </interface>")
    print("</protocol>")
    sys.stderr.write("interfaces: %s\n" % ", ".join(i.name.decode() for i in out))


if __name__ == "__main__":
    main()
