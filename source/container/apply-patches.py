#!/usr/bin/env python3
"""apply-patches.py: apply patches/*.patch (in name order) to the clean chromium151 checkout, keeping timestamps
stable so ninja only rebuilds what really changed.

Why: the source snapshot is always clean upstream. Applying a patch rewrites the file, which gives it a new
timestamp, and ninja would then rebuild everything that includes it on EVERY build. So we remember, per patched file,
the sha256 of its content and the timestamp we gave it last time (snap/patch-state.json):
  - same content as last time  -> put the old timestamp back (no rebuild)
  - new or changed content      -> timestamp = now (rebuild)
  - no longer patched           -> timestamp = now (the file went back to upstream content: rebuild)

Patches must be made from the repo root (paths start with "src/"), e.g.
  git -C /work/c151 diff -- src/ui/ozone/... > patches/0001-short-name.patch
Environment: REPO, W, SNAP (set by lib.sh).
"""
import glob
import hashlib
import json
import os
import subprocess
import sys
import time

REPO, W, SNAP = os.environ["REPO"], os.environ["W"], os.environ["SNAP"]
PATCHES = sorted(glob.glob("/opt/cn/patches/*.patch"))
STATE_IN = os.path.join(SNAP, "patch-state.json")
STATE_OUT = os.path.join(W, "patch-state.json")


def git(*a, **kw):
    return subprocess.run(["git", "-C", REPO, *a], check=True, capture_output=True, text=True, **kw).stdout


def sha(p):
    with open(p, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def main():
    old = {}
    if os.path.isfile(STATE_IN):
        with open(STATE_IN) as f:
            old = json.load(f)
    # tracked files changed before patching: generated by setup hooks (e.g. lastchange) are fine, but a patched
    # file must start clean
    dirty = {l[3:] for l in git("status", "--porcelain", "--untracked-files=no").splitlines() if l.strip()}
    paths = []
    for p in PATCHES:
        for line in git("apply", "--numstat", p).splitlines():
            paths.append(line.split("\t", 2)[2])
    clash = dirty & set(paths)
    if clash:
        sys.exit("files to patch are already modified in the snapshot: " + " ".join(sorted(clash)))
    if dirty:
        print(f"note: {len(dirty)} tracked files differ from git (generated by setup): " + " ".join(sorted(dirty)[:10]))
    # every patch, in name order (an early version of this block applied only the last patch, and only when the
    # snapshot was dirty)
    for p in PATCHES:
        try:
            git("apply", "--whitespace=nowarn", p)
        except subprocess.CalledProcessError as e:
            sys.exit(f"patch does not apply: {os.path.basename(p)}\n{e.stderr}")
        print("applied", os.path.basename(p))
    now = time.time()
    new, rebuilt = {}, []
    for rel in sorted(set(paths)):
        full = os.path.join(REPO, rel)
        if not os.path.isfile(full):
            continue
        h = sha(full)
        prev = old.get(rel)
        if prev and prev["sha"] == h:
            os.utime(full, (prev["mtime"], prev["mtime"]))
            new[rel] = prev
        else:
            os.utime(full, (now, now))
            new[rel] = {"sha": h, "mtime": now}
            rebuilt.append(rel)
    for rel in old:
        if rel not in new and os.path.isfile(os.path.join(REPO, rel)):
            os.utime(os.path.join(REPO, rel), (now, now))
            rebuilt.append(rel + " (patch removed)")
    with open(STATE_OUT, "w") as f:
        json.dump(new, f, indent=1, sort_keys=True)
    print(f"{len(PATCHES)} patches, {len(new)} patched files, {len(rebuilt)} will rebuild:", *rebuilt[:30], sep="\n  ")


if __name__ == "__main__":
    main()
